const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
require.extensions[".ts"] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename);
const { normalizeAircraft, normalizeFeed } = require("../src/lib/normalize.ts");
const geo = require("../src/lib/geo.ts");
const units = require("../src/lib/units.ts");
const style = require("../src/lib/aircraftStyle.ts");
assert.equal(normalizeAircraft(null), null);
assert.equal(normalizeAircraft({ hex: " " }), null);
assert.deepEqual(normalizeFeed({}), []);
assert.deepEqual(normalizeFeed(null), []);
const ac = normalizeAircraft({ hex: " ABC123 ", flight: " TEST ", r: "G-TEST", t: "A320", dbFlags: 3, true_heading: 90, geom_rate: 100, lastPosition: { lat: 52, lon: -1 }, gs: 0 });
assert.equal(ac.hex, "abc123");
assert.equal(ac.flight, "TEST");
assert.equal(ac.reg, "G-TEST");
assert.equal(ac.isMilitary, true);
assert.equal(ac.isInteresting, true);
assert.equal(ac.track, 90);
assert.equal(ac.baro_rate, 100);
assert.equal(ac.lat, 52);
assert.equal(ac.lon, -1);
assert.equal(ac.gs, 0);
assert.equal(ac.alt_baro, null);
assert.equal(normalizeAircraft({ hex: "abc123", track: 0, true_heading: 90 }).track, 0);
assert.equal(normalizeAircraft({ hex: "abc123", alt_baro: "ground" }).alt_baro, "ground");
for (const key of ["ac", "aircraft"]) assert.equal(normalizeFeed({ [key]: [{ hex: "abc123" }, {}] }).length, 1);
assert.equal(geo.distanceNm(0, 0, 0, 0), 0);
const point = geo.destinationPoint(52, -1, 90, 60);
assert.ok(Math.abs(geo.distanceNm(52, -1, point[1], point[0]) - 60) < 1e-8);
assert.deepEqual(geo.deadReckon(52, -1, 60, 90, 3600), point);
const ring = geo.circlePolygon(52, -1, 50);
assert.equal(ring.length, 129);
assert.deepEqual(ring[0], ring[128]);
assert.equal(units.formatAltitude(null, "metric"), "—");
assert.equal(units.formatAltitude("ground", "aviation"), "Ground");
assert.equal(units.formatAltitude(1000, "metric"), "305 m");
assert.equal(units.formatSpeed(100, "metric"), "185 km/h");
assert.equal(units.formatDistance(10, "metric"), "18.5 km");
assert.equal(units.formatVerticalRate(1000, "metric"), "5.1 m/s");
for (const fn of ["formatSpeed", "formatDistance", "formatVerticalRate"]) assert.equal(units[fn](null, "aviation"), "—");
assert.equal(style.altitudeColor(5000), "#f59e0b");
assert.equal(style.altitudeColor(10000), "#22d3ee");
assert.equal(style.altitudeColor(25000), "#818cf8");
assert.equal(style.altitudeColor(4999), "#10b981");
assert.equal(style.isEmergency("7700"), true);
assert.equal(style.isEmergency(null), false);
assert.equal(style.iconKind(ac), "military");
for (const [category, expected] of [["A7", "helicopter"], ["A5", "heavy"], ["A4", "jet"], ["A3", "jet"], ["A2", "light"], [null, "jet"]]) assert.equal(style.iconKind({ ...ac, isMilitary: false, category }), expected);
console.log("PASS: normalization (normal, empty, malformed), geo, units, and aircraft styles");
